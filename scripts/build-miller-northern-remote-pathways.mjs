function resource({
  id, name, organization, province, categories, description, serviceArea, website,
  phone, email, access, community, address, local = [], regional = [], search = [],
  provinceWide = false, navigationOnly = false, virtual = false, travelRequired = false,
  population = "People seeking the listed practical service", eligibility,
  transportation, visibility = ["miller"], scopeNote, pathway,
}) {
  return {
    canonical_resource_id: id,
    project_visibility: visibility,
    name,
    organization,
    categories,
    description,
    population_served: population,
    province,
    community,
    address,
    physical_location: community ? { community, address, province } : undefined,
    local_service_area: local.length ? local : community ? [community] : undefined,
    regional_service_area: regional.length ? regional : undefined,
    search_locations: search.length ? search : undefined,
    province_wide: provinceWide,
    navigation_only: navigationOnly,
    virtual,
    travel_required: travelRequired,
    service_area: serviceArea,
    scope_note: scopeNote,
    delivery_modes: [...new Set([community ? "in person" : null, !community && navigationOnly && !virtual ? "navigation" : null, virtual ? "virtual" : null].filter(Boolean))],
    referral_requirements: access,
    access_pathway: access,
    eligibility,
    phone,
    email,
    website,
    transportation,
    navigation_pathway: pathway ? {
      ...pathway,
      travel_required: travelRequired,
      source_provenance: pathway.source_provenance || { authority: organization, url: website },
    } : undefined,
    source: { title: name, authority: organization, url: website },
    last_verified_date: verified,
  }
}

